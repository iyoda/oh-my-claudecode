#!/usr/bin/env node
/**
 * Regenerates the frozen ledgers that identify files installed by OMC before the
 * install manifest (<config dir>/.omc-managed-assets.json) existed:
 *   src/installer/historical-agent-ownership.ts  (safe top-level agents/*.md)
 *   src/installer/historical-hook-ownership.ts   (templates/hooks/*.mjs named in OMC_HOOK_FILENAMES)
 *
 * Usage: node scripts/generate-historical-install-ownership.mjs
 * Requires the local v4.* and v5.* release tags up to FROZEN_LAST_TAG.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
// Later releases are identified by the manifest, so the walk must not grow past this tag.
const FROZEN_FIRST_TAG = 'v4.0.0';
const FROZEN_LAST_TAG = 'v5.7.31';

const git = (...args) => execFileSync('git', args, { cwd: repoRoot, maxBuffer: 64 * 1024 * 1024 });

const parseTag = tag => tag.slice(1).split('.').map(Number);
function compareTags(left, right) {
  const [a, b] = [parseTag(left), parseTag(right)];
  return a[0] - b[0] || a[1] - b[1] || a[2] - b[2];
}

const tags = git('tag', '-l', 'v4.*', 'v5.*').toString().split('\n')
  .filter(tag => /^v[45]\.\d+\.\d+$/.test(tag) && compareTags(tag, FROZEN_LAST_TAG) <= 0)
  .sort(compareTags);
if (tags[0] !== FROZEN_FIRST_TAG || tags.at(-1) !== FROZEN_LAST_TAG) {
  throw new Error(`Expected local tags ${FROZEN_FIRST_TAG} through ${FROZEN_LAST_TAG}; found ${tags[0]} through ${tags.at(-1)}`);
}

function collectRecords(treePath, isOwnedFilename) {
  const byBlob = new Map();
  for (const tag of tags) {
    for (const line of git('ls-tree', tag, `${treePath}/`).toString().split('\n')) {
      const match = line.match(/^100\d{3} blob ([a-f0-9]{40})\t(.+)$/);
      if (!match) continue;
      const [, gitBlob, path] = match;
      const filename = path.slice(treePath.length + 1);
      if (!isOwnedFilename(filename)) continue;
      const key = `${filename}\0${gitBlob}`;
      const record = byBlob.get(key);
      if (record) {
        record.lastReleaseTag = tag;
      } else {
        const content = git('cat-file', 'blob', gitBlob);
        byBlob.set(key, {
          filename,
          byteLength: content.length,
          sha256: createHash('sha256').update(content).digest('hex'),
          gitBlob,
          firstReleaseTag: tag,
          lastReleaseTag: tag,
        });
      }
    }
  }
  return [...byBlob.values()].sort((left, right) =>
    left.filename < right.filename ? -1
      : left.filename > right.filename ? 1
        : compareTags(left.firstReleaseTag, right.firstReleaseTag));
}

const formatRecord = record =>
  `  { filename: '${record.filename}', byteLength: ${record.byteLength}, sha256: '${record.sha256}', gitBlob: '${record.gitBlob}', firstReleaseTag: '${record.firstReleaseTag}', lastReleaseTag: '${record.lastReleaseTag}' },`;

function header(subject, sourceDescription) {
  return `/**
 * Exact ownership records for ${subject} shipped by local v4 and v5 release tags.
 *
 * The inventory is generated by scripts/generate-historical-install-ownership.mjs from
 * ${sourceDescription} in the local
 * ${FROZEN_FIRST_TAG} through ${FROZEN_LAST_TAG} tags. A record authorizes only the exact filename, byte
 * length, and SHA-256 bytes; release tags and the git blob provide audit provenance.
 *
 * This inventory is a frozen bootstrap for installs that predate the install manifest
 * (.omc-managed-assets.json). It never needs new entries: later installs use the manifest.
 *
 * Do not replace this with filename, frontmatter, or fuzzy ownership heuristics.
 */
`;
}

function writeLedger(relativePath, source) {
  writeFileSync(join(repoRoot, relativePath), source);
  console.log(`Wrote ${relativePath}`);
}

const agentRecords = collectRecords('agents', filename => /^[a-z0-9-]+\.md$/.test(filename));
writeLedger('src/installer/historical-agent-ownership.ts', `${header('standalone agent files', 'each safe top-level agents/*.md path')}
export interface HistoricalAgentOwnership {
  filename: string;
  byteLength: number;
  sha256: string;
  gitBlob: string;
  firstReleaseTag: string;
  lastReleaseTag: string;
}

export const HISTORICAL_AGENT_OWNERSHIP: readonly HistoricalAgentOwnership[] = [
${agentRecords.map(formatRecord).join('\n')}
];
`);

const installerSource = readFileSync(join(repoRoot, 'src/installer/index.ts'), 'utf-8');
const hookFilenamesBlock = installerSource.match(/const OMC_HOOK_FILENAMES = new Set\(\[([\s\S]*?)\]\)/);
if (!hookFilenamesBlock) throw new Error('OMC_HOOK_FILENAMES not found in src/installer/index.ts');
const hookFilenames = new Set([...hookFilenamesBlock[1].matchAll(/'([^']+)'/g)].map(match => match[1]));

const hookRecords = collectRecords('templates/hooks', filename => hookFilenames.has(filename));
writeLedger('src/installer/historical-hook-ownership.ts', `${header('standalone hook scripts', 'each top-level templates/hooks/*.mjs path named in OMC_HOOK_FILENAMES')}
import type { HistoricalAgentOwnership } from './historical-agent-ownership.js';

export const HISTORICAL_HOOK_OWNERSHIP: readonly HistoricalAgentOwnership[] = [
${hookRecords.map(formatRecord).join('\n')}
];
`);
